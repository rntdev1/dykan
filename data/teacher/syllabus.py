# Subjects where a task usually has a number as its answer.
NUMERIC_SUBJECTS = frozenset({"Математика", "Алгебра", "Геометрія", "Фізика", "Хімія"})


# Subjects the teacher is not reliable enough to write about unaided. For Ukrainian
# grammar its explanations passed the fact-check only 11% of the time, and ones
# that passed still used wrong terms (e.g. "визначальні" for "означальні"
# clauses). For this subject training uses real exam tasks only.
UNRELIABLE_FOR_TEACHER = frozenset({"Українська мова"})


def topics(include_unreliable: bool = False) -> list[tuple[str, int, str]]:
    return [(subject, grade, topic) for subject, items in SYLLABUS.items() for grade, topic in items
            if include_unreliable or subject not in UNRELIABLE_FOR_TEACHER]
