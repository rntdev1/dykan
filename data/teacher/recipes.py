# ---------- shared helpers ----------

_SECTION_RE = re.compile(r"^\s*(?:#{1,4}|\*\*)?\s*(ЗАВДАННЯ|РОЗВ['’ʼ`]ЯЗАННЯ|ВІДПОВІДЬ)\s*:?\s*(?:\*\*)?\s*:?\s*$", re.MULTILINE | re.IGNORECASE)
_NUMBER_RE = re.compile(r"-?\d+(?:[.,]\d+)?")


def split_sections(text: str) -> dict[str, str] | None:
    """Parse '### ЗАВДАННЯ / ### РОЗВ'ЯЗАННЯ / ### ВІДПОВІДЬ' output."""
    marks = list(_SECTION_RE.finditer(text))
    names = [m.group(1).upper().replace("’", "'").replace("ʼ", "'").replace("`", "'") for m in marks]
    if names != ["ЗАВДАННЯ", "РОЗВ'ЯЗАННЯ", "ВІДПОВІДЬ"]:
        return None
    bodies = [text[m.end(): (marks[i + 1].start() if i + 1 < len(marks) else len(text))].strip() for i, m in enumerate(marks)]
    if not all(bodies):
        return None
    return {"task": bodies[0], "solution": bodies[1], "answer": bodies[2]}


def final_answer(text: str) -> str:
    """Text after the last 'Відповідь:' marker (the whole text if absent)."""
    parts = re.split(r"відповідь\s*[:—-]", text, flags=re.IGNORECASE)
    return parts[-1].strip() if len(parts) > 1 else text.strip()


def _norm(text: str) -> str:
    return re.sub(r"[^\w]+", " ", text.lower().replace("’", "'"), flags=re.UNICODE).strip()


def answers_match(kind: str, expected: str, got: str) -> bool:
    """Do two final answers agree? kind: choice | number | short."""
    if kind == "choice":
        # Capital letters only: lowercase "б", "в", "а" are ordinary Ukrainian words.
        pick = lambda s: next(iter(re.findall(r"(?<![\w'’])([АБВГ])(?![\w'’])", s)), None)
        a, b = pick(expected), pick(got)
        return a is not None and a == b
    if kind == "number":
        num = lambda s: [float(x.replace(",", ".")) for x in _NUMBER_RE.findall(s.replace("−", "-"))]
        a, b = num(expected), num(got)
        return bool(a and b) and abs(a[0] - b[0]) <= 1e-3 * max(1.0, abs(a[0]))
    a, b = _norm(expected), _norm(got)
    if not a or not b:
        return False
    if _NUMBER_RE.search(expected) and _NUMBER_RE.search(got):  # "4" vs "4 °C", "1648" vs "1648 рік"
        return answers_match("number", expected, got)
    wa, wb = set(a.split()), set(b.split())
    return a == b or wa <= wb or wb <= wa


