_TURN_RE = re.compile(r"^\s*\**(УЧЕНЬ|ДИКАНЬ)\**\s*:\**\s*", re.MULTILINE | re.IGNORECASE)


def parse_dialogue(text: str) -> list[dict] | None:
    """'УЧЕНЬ: ... / ДИКАНЬ: ...' text -> chat messages. Must alternate, start with
    the student, end with Дикань and have at least two exchanges."""
    marks = list(_TURN_RE.finditer(text))
    if len(marks) < 4 or len(marks) % 2:
        return None
    messages = []
    for i, m in enumerate(marks):
        role = "user" if m.group(1).upper() == "УЧЕНЬ" else "assistant"
        if role != ("user" if i % 2 == 0 else "assistant"):
            return None
        body = text[m.end(): marks[i + 1].start() if i + 1 < len(marks) else len(text)].strip()
        if not body:
            return None
        messages.append({"role": role, "content": body})
    return messages


