def explain_jobs(n: int, seed: int) -> list[dict]:
    rng, pool = random.Random(seed), topics()
    return [{"id": f"explain-{seed}-{i}", **dict(zip(("subject", "grade", "topic"), pool[i % len(pool)] if i < len(pool) else rng.choice(pool))),
             "ask": rng.choice(EXPLAIN_ASK), "words": rng.choice(["250–400", "400–600", "600–800"])} for i in range(n)]


def make_explanation(teacher: Teacher, job: dict) -> dict:
    question = job["ask"].format(**job)
    text, tokens = teacher.chat([{"role": "system", "content": EXPLAIN_SYSTEM},
                                 {"role": "user", "content": f"{question}\n\n(Обсяг відповіді: приблизно {job['words']} слів.)"}], max_tokens=1600, temperature=0.8)
    row = dict(job, text=text.strip(), completion_tokens=tokens)
    if len(text.split()) < 120:
        return dict(row, verdict="too_short")
    if "$" in text or "\\frac" in text or "\\(" in text:
        return dict(row, verdict="latex")
    if not clean_ukrainian(text) and job["subject"] != "Англійська мова":
        return dict(row, verdict="not_clean")
    ok, note, tokens = fact_check(teacher, f"Тема: {job['topic']} ({job['subject']}, {job['grade']} клас).", text)
    row["completion_tokens"] += tokens
    if not ok:
        return dict(row, verdict="failed_fact_check", fact_check=note)
    row["messages"] = [{"role": "user", "content": question}, {"role": "assistant", "content": text.strip()}]
    return dict(row, verdict="ok")


