def chat_jobs(n: int, seed: int) -> list[dict]:
    rng = random.Random(seed)
    return [{"id": f"chat-{seed}-{i}", "topic": rng.choice(CHAT_TOPICS), "age": rng.randint(10, 17), "follow_up": rng.random() < 0.4,
             "variant": rng.randint(1, 10**6)} for i in range(n)]


def make_chat(teacher: Teacher, job: dict) -> dict:
    row = dict(job, completion_tokens=0)

    def say(system: str, messages: list[dict], max_tokens: int, temperature: float) -> str:
        text, tokens = teacher.chat([{"role": "system", "content": system}] + messages, max_tokens=max_tokens, temperature=temperature)
        row["completion_tokens"] += tokens
        return text.strip().strip('"«»')

    question = say(ASKER_SYSTEM, [{"role": "user", "content": f"Тема повідомлення: {job['topic']}. Вік учня: {job['age']}. Варіант {job['variant']}."}], 250, 1.0)
    if not question or len(question) > 1200:
        return dict(row, verdict="bad_question")
    messages = [{"role": "user", "content": question}]
    messages.append({"role": "assistant", "content": say(CHAT_PERSONA, messages, 900, 0.7)})
    if job["follow_up"]:
        transcript = f"Учень: {question}\n\nАсистент: {messages[-1]['content']}"
        follow = say(ASKER_SYSTEM, [{"role": "user", "content": f"Ось початок розмови:\n{transcript}\n\nНапиши наступне коротке повідомлення учня: уточнення, заперечення або нове прохання за темою."}], 200, 1.0)
        if follow:
            messages.append({"role": "user", "content": follow})
            messages.append({"role": "assistant", "content": say(CHAT_PERSONA, messages, 900, 0.7)})
    text = "\n".join(m["content"] for m in messages)
    if any(not m["content"] for m in messages):
        return dict(row, verdict="empty_turn")
    if "$" in text or "\\frac" in text:
        return dict(row, verdict="latex")
    if not clean_ukrainian(text) and "англійськ" not in job["topic"]:
        return dict(row, verdict="not_clean")
    answers = "\n\n".join(m["content"] for m in messages if m["role"] == "assistant")
    ok, note, tokens = fact_check(teacher, f"Розмова учня з асистентом. Запит учня: {question}", answers)
    row["completion_tokens"] += tokens
    if not ok:
        return dict(row, verdict="failed_fact_check", fact_check=note)
    return dict(row, verdict="ok", messages=messages)


