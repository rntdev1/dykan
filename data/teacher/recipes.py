def slots(text: str) -> list[str]:
    return sorted({m.group().lower() for m in _SLOT_RE.finditer(text)})


def reword_keeps_facts(original: str, reworded: str) -> bool:
    low = reworded.lower()
    return all(slot in low for slot in slots(original))


def make_tool_episode(teacher: Teacher, episode: Episode, job: dict) -> dict:
    row = dict(job, family=episode.family, completion_tokens=0)
    user = episode.user
    if job["reword"]:
        ask = f"Стиль: {REWORD_STYLES[job['style'] % len(REWORD_STYLES)]}.\n\nЗапит: {episode.user}" if "style" in job else episode.user
        text, tokens = teacher.chat([{"role": "system", "content": REWORD_SYSTEM}, {"role": "user", "content": ask}], max_tokens=200, temperature=1.0)
        row["completion_tokens"] += tokens
        text = re.sub(r"^\s*Запит\s*:\s*", "", text).strip().strip('"')
        text = re.sub(r"«([а-яіїєґ' ]+)»", r"\1", text)  # the teacher likes to quote «алгебри»; pupils do not
        if text and reword_keeps_facts(episode.user, text) and clean_ukrainian(text) and len(text) < 3 * len(episode.user) + 40:
            user = text
        else:
            row["reword_rejected"] = text[:200]
    messages = episode.messages()
    messages[1]["content"] = user
    steps = [{"call": m["tool_calls"][0]["function"], "result": m["tool_responses"][0]["response"]} for m in messages[2:-1]]
    if steps:  # no-tool episodes keep their scripted answer
        context = f"Запит учня: {user}\n\nРезультати інструментів:\n{json.dumps(steps, ensure_ascii=False, indent=1)}"
        answer, tokens = teacher.chat([{"role": "system", "content": ANSWER_SYSTEM}, {"role": "user", "content": context}], max_tokens=500, temperature=0.6)
        row["completion_tokens"] += tokens
        answer = answer.strip()
        if not answer or not clean_ukrainian(answer) or re.search(r"\b(hw|task|[tpc])\d+\b", answer):
            return dict(row, verdict="bad_answer", answer=answer[:300])
        messages[-1]["content"] = answer
    return dict(row, verdict="ok", messages=messages, tools=episode.tools)


