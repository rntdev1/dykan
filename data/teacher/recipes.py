def task_jobs(n: int, seed: int) -> list[dict]:
    rng, pool, jobs = random.Random(seed), topics(), []
    for i in range(n):
        subject, grade, topic = pool[i % len(pool)] if i < len(pool) else rng.choice(pool)
        kinds = ["number", "number", "choice", "short"] if subject in NUMERIC_SUBJECTS else ["choice", "choice", "short"]
        jobs.append({"id": f"task-{seed}-{i}", "subject": subject, "grade": grade, "topic": topic, "kind": rng.choice(kinds),
                     "level": rng.choice(LEVELS), "ask": rng.choice(ASK), "variant": rng.randint(1, 10**6)})
    return jobs


def make_task(teacher: Teacher, job: dict) -> dict:
    row = dict(job, completion_tokens=0)
    prompt = (
        f"Склади одне завдання для {job['grade']} класу. Предмет: {job['subject']}. Тема: {job['topic']}.\n"
        f"Тип: {KINDS[job['kind']]}.\nСкладність: {job['level']}.\n"
        f"Номер варіанта {job['variant']}: зроби завдання несхожим на типові приклади з цієї теми.\n\n"
        "Дотримуйся точно такого формату:\n### ЗАВДАННЯ\n(умова)\n### РОЗВ'ЯЗАННЯ\n(покрокове пояснення для учня)\n### ВІДПОВІДЬ\n(лише остаточна відповідь)"
    )
    text, tokens = teacher.chat([{"role": "system", "content": TASK_SYSTEM}, {"role": "user", "content": prompt}], max_tokens=900)
    row["completion_tokens"] += tokens
    parts = split_sections(text)
    if parts is None:
        return dict(row, verdict="bad_format", raw=text[:700])
    if "$" in text or "\\frac" in text or "\\(" in text:
        return dict(row, verdict="latex", raw=text[:300])
    row.update(parts)
    if not clean_ukrainian(parts["task"] + "\n" + parts["solution"]) and job["subject"] != "Англійська мова":
        return dict(row, verdict="not_clean")

    solve_system = "Ти розв'язуєш шкільне завдання. Міркуй коротко й останнім рядком напиши «Відповідь: » і лише остаточну відповідь."
    for _ in range(2):
        solved, tokens = teacher.chat([{"role": "system", "content": solve_system}, {"role": "user", "content": parts["task"]}], max_tokens=700)
        row["completion_tokens"] += tokens
        if not answers_match(job["kind"], parts["answer"], final_answer(solved)):
            return dict(row, verdict="blind_solve_disagrees", blind=final_answer(solved)[:200])

    ok, note, tokens = fact_check(teacher, f"Завдання:\n{parts['task']}\n\nПравильна відповідь: {parts['answer']}", parts["solution"])
    row["completion_tokens"] += tokens
    if not ok:
        return dict(row, verdict="failed_fact_check", fact_check=note)
    row["messages"] = [{"role": "user", "content": job["ask"].format(task=parts["task"])},
                       {"role": "assistant", "content": f"{parts['solution']}\n\nВідповідь: {parts['answer']}"}]
    return dict(row, verdict="ok")


