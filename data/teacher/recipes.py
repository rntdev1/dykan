def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("recipe", choices=["tasks", "explain", "tools", "tools2", "anytools", "tutor", "chat"])
    ap.add_argument("--n", type=int, required=True)
    ap.add_argument("--model", required=True)
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--base-url", default="http://127.0.0.1:8000/v1")
    ap.add_argument("--workers", type=int, default=96)
    ap.add_argument("--seed", type=int, default=1)
    args = ap.parse_args()
    teacher = Teacher(args.model, args.base_url)

    if args.recipe == "tasks":
        jobs, work = task_jobs(args.n, args.seed), lambda job: make_task(teacher, job)
    elif args.recipe == "explain":
        jobs, work = explain_jobs(args.n, args.seed), lambda job: make_explanation(teacher, job)
    elif args.recipe == "tutor":
        jobs, work = tutor_jobs(args.n, args.seed), lambda job: make_dialogue(teacher, job)
    elif args.recipe == "chat":
        jobs, work = chat_jobs(args.n, args.seed), lambda job: make_chat(teacher, job)
    elif args.recipe == "anytools":
        jobs, work = anytool_jobs(args.n, args.seed), lambda job: make_anytool_episode(teacher, job)
    elif args.recipe == "tools2":  # the wide training generator, with a rewording style per job
        episodes = generate_train(args.n, seed=args.seed)
        rng = random.Random(args.seed)
        jobs = [{"id": f"tools2-{args.seed}-{i}", "index": i, "reword": rng.random() < 0.85, "style": rng.randrange(len(REWORD_STYLES))} for i in range(len(episodes))]
        work = lambda job: make_tool_episode(teacher, episodes[job["index"]], job)
    else:
        episodes = generate(args.n, seed=args.seed, train=True)
        rng = random.Random(args.seed)
        jobs = [{"id": f"tools-{args.seed}-{i}", "index": i, "reword": rng.random() < 0.8} for i in range(len(episodes))]
        work = lambda job: make_tool_episode(teacher, episodes[job["index"]], job)

    stats = run_jobs(jobs, work, args.out, workers=args.workers)
    rows = [json.loads(line) for line in args.out.read_text(encoding="utf-8").splitlines() if line.strip()]
    verdicts = Counter(r.get("verdict", "error") for r in rows)
    summary = {"recipe": args.recipe, "rows": len(rows), "accepted": verdicts.get("ok", 0),
               "acceptance_rate": round(verdicts.get("ok", 0) / len(rows), 4) if rows else None, "verdicts": dict(verdicts.most_common()), "run": stats}
    args.out.with_suffix(".summary.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False), encoding="utf-8")
    print(json.dumps(summary, indent=2, ensure_ascii=False))


if __name__ == "__main__":
    main()
