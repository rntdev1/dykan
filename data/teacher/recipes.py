def parse_json_object(text: str) -> dict | None:
    text = re.sub(r"^```(?:json)?\s*|\s*```$", "", text.strip())
    start, end = text.find("{"), text.rfind("}")
    try:
        value = json.loads(text[start:end + 1]) if start >= 0 and end > start else None
    except ValueError:
        return None
    return value if isinstance(value, dict) else None


def check_arguments(schema: dict, arguments: dict) -> str | None:
    """None if the arguments fit the declared parameters, else what is wrong."""
    props = schema.get("properties", {})
    if not isinstance(arguments, dict):
        return "arguments are not an object"
    for key in schema.get("required", []):
        if key not in arguments:
            return f"missing required {key}"
    for key, value in arguments.items():
        if key not in props:
            return f"undeclared parameter {key}"
        kind = _JSON_TYPES.get(props[key].get("type"))
        if kind is None or not isinstance(value, kind) or (isinstance(value, bool) and props[key].get("type") in ("integer", "number")):
            return f"wrong type for {key}"
        if "enum" in props[key] and value not in props[key]["enum"]:
            return f"{key} not in enum"
    return None


def check_anytool_episode(data: dict, scenario: str) -> str | None:
    """None if the generated episode is well-formed for its scenario, else the reason."""
    tools, steps = data.get("tools"), data.get("steps")
    if not isinstance(tools, list) or not 2 <= len(tools) <= 5 or not isinstance(steps, list):
        return "bad_tools"
    if not all(isinstance(data.get(k), str) and data[k].strip() for k in ("user", "final")):
        return "bad_text"
    schemas = {}
    for tool in tools:
        params = tool.get("parameters") if isinstance(tool, dict) else None
        if (not isinstance(params, dict) or not isinstance(tool.get("name"), str) or not _TOOL_NAME_RE.match(tool["name"]) or tool["name"] in schemas
                or not isinstance(tool.get("description"), str) or params.get("type") != "object" or not isinstance(params.get("properties"), dict)
                or not all(isinstance(p, dict) and p.get("type") in _JSON_TYPES for p in params["properties"].values())
                or not set(params.get("required", [])) <= set(params["properties"])):
            return "bad_schema"
        schemas[tool["name"]] = params
    _, lo, hi = ANYTOOL_SCENARIOS[scenario]
    if not lo <= len(steps) <= hi:
        return "wrong_step_count"
    earlier = ""
    for i, step in enumerate(steps):
        if not isinstance(step, dict) or step.get("name") not in schemas or not isinstance(step.get("result"), dict) or not step["result"]:
            return "bad_step"
        if check_arguments(schemas[step["name"]], step.get("arguments")):
            return "arguments_do_not_fit_schema"
        # In a chain, a later call has to use something the earlier results returned.
        if scenario == "chain" and i > 0 and not any(
                str(v) in earlier for v in step["arguments"].values() if isinstance(v, (str, int)) and not isinstance(v, bool) and len(str(v)) >= 2):
            return "chain_does_not_use_results"
        earlier += json.dumps(step["result"], ensure_ascii=False)
    if scenario == "error" and not any("error" in step["result"] for step in steps):
        return "no_error_in_result"
    if scenario != "error" and any("error" in step["result"] for step in steps):
        return "unexpected_error"
    if any(tool["name"] in data["user"] or tool["name"] in data["final"] for tool in tools):
        return "tool_name_in_text"
    return None


def make_anytool_episode(teacher: Teacher, job: dict) -> dict:
    row = dict(job, completion_tokens=0)
    today = date.fromisoformat(job["today"])
    ask = (f"Галузь: {job['domain']}.\nСценарій: {ANYTOOL_SCENARIOS[job['scenario']][0]}.\nСтиль назв інструментів і параметрів: {job['naming']}.\n"
           f"Сьогодні {WEEKDAY_NOM[today.weekday()]}, {job['today']}, зараз {job['clock']}.\nВаріант {job['variant']}.")
    text, tokens = teacher.chat([{"role": "system", "content": ANYTOOL_SYSTEM}, {"role": "user", "content": ask}], max_tokens=1400, temperature=0.9)
    row["completion_tokens"] += tokens
    data = parse_json_object(text)
    if data is None:
        return dict(row, verdict="bad_json")
    problem = check_anytool_episode(data, job["scenario"])
    if problem:
        return dict(row, verdict=problem)
    said = data["user"] + "\n" + data["final"]
    if not clean_ukrainian(said) or "$" in said or "**" in said:
        return dict(row, verdict="not_clean")
    tools = [{"type": "function", "function": {"name": t["name"], "description": t["description"], "parameters": t["parameters"]}} for t in data["tools"]]
    shown = json.dumps({"tools": data["tools"], "user": data["user"], "steps": data["steps"], "final": data["final"]}, ensure_ascii=False, indent=1)
    verdict, tokens = teacher.chat([{"role": "system", "content": ANYTOOL_JUDGE}, {"role": "user", "content": f"Сьогодні {job['today']}.\n\n{shown}"}], max_tokens=120, temperature=0.0)
    row["completion_tokens"] += tokens
    if not verdict.strip().upper().startswith("ТАК"):
        return dict(row, verdict="judge_rejected", judge=verdict.strip()[:300])
    messages = [] if job["prompt"] == "none" else [{"role": "system", "content": system_prompt(today, job["clock"], calendar=job["prompt"] == "calendar")}]
    messages.append({"role": "user", "content": data["user"].strip()})
    for step in data["steps"]:
        messages.append({"role": "assistant", "tool_calls": [{"type": "function", "function": {"name": step["name"], "arguments": step["arguments"]}}],
                         "tool_responses": [{"name": step["name"], "response": step["result"]}]})
    messages.append({"role": "assistant", "content": data["final"].strip()})
    return dict(row, verdict="ok", messages=messages, tools=tools)


